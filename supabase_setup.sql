create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Sweets',
  price numeric(10,2) not null default 0,
  unit text not null default 'kg',
  emoji text default '🍬',
  image_url text,
  tag text default 'FRESH',
  active boolean not null default true,
  sort_order integer not null default 100
);

create table if not exists public.site_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_name text,
  phone text,
  items jsonb not null default '[]'::jsonb,
  total numeric(10,2) not null default 0,
  status text not null default 'new',
  notes text,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.site_settings enable row level security;
alter table public.orders enable row level security;

-- Public can view active products. Only the one named admin can change products.
drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products" on public.products for select using (active = true or auth.jwt()->>'email' = 'admin@example.com');
drop policy if exists "Admin manages products" on public.products;
create policy "Admin manages products" on public.products for all using (auth.jwt()->>'email' = 'admin@example.com') with check (auth.jwt()->>'email' = 'admin@example.com');

-- Public can read store settings; only admin can change them.
drop policy if exists "Public reads settings" on public.site_settings;
create policy "Public reads settings" on public.site_settings for select using (true);
drop policy if exists "Admin manages settings" on public.site_settings;
create policy "Admin manages settings" on public.site_settings for all using (auth.jwt()->>'email' = 'admin@example.com') with check (auth.jwt()->>'email' = 'admin@example.com');

-- Customers can submit orders/enquiries; only admin can view or update them.
drop policy if exists "Customers create orders" on public.orders;
create policy "Customers create orders" on public.orders for insert with check (true);
drop policy if exists "Admin views orders" on public.orders;
create policy "Admin views orders" on public.orders for select using (auth.jwt()->>'email' = 'admin@example.com');
drop policy if exists "Admin updates orders" on public.orders;
create policy "Admin updates orders" on public.orders for update using (auth.jwt()->>'email' = 'admin@example.com') with check (auth.jwt()->>'email' = 'admin@example.com');

